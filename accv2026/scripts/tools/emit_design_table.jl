# =============================================================================
# emit_design_table.jl — MAIN-PAPER TABLE 1 (tab:design, figures/table_design.tex):
# the optimizer taxonomy (objective rows × optimization-path columns) with each
# arm's isolated single-threaded per-call time [ms] from the timing sidecar of
# timing_table.jl stage time_pt (PhotoTourism, deployed operating points,
# 25-update cap). The grid is the paper's fixed design; only the numbers are
# read from data — the same per-call formula as the supplement's timing table
# (lo_ns_total / lo_calls_total; TLS-IRLS and TLS-LZ ride the Stu-t run's
# :msac / :lezach refit columns).
#
#   julia --project=. scripts/emit_design_table.jl --timing=<lo_timing_pt_*.jld2> --out=<table_design.tex>
# =============================================================================
using DrWatson; @quickactivate "ACCV2026"
using JLD2, Printf
include(srcdir("config.jl"))

const TIMING = cli_option(ARGS, "timing", "")
const OUT    = cli_option(ARGS, "out", "")
(isempty(TIMING) || isempty(OUT)) && error("emit_design_table: --timing and --out are required")

runs = JLD2.load(TIMING)["runs"]
# Cells carry the per-call µs only: an arm's name composes as objective–path
# (Welsch-HQ, TLS-GNC, …), stated in the caption. Arms the convention does not
# name (TLS-LZ, TLS-LO+, Stu-tU-BCD) keep a short "-tag" in their cell, the
# hyphen marking that it composes with the row objective.
# ms per call, two decimal places throughout (0.30, 0.57, 1.23).
# The cells are arms of the arm table, read through figure_style.jl `arm_lo_us_per_call`.
num(key) = @sprintf("%.2f", arm_lo_us_per_call(runs, key) / 1e3)
tagged(label, key) = @sprintf("-%s~%s", label, num(key))   # leading hyphen: composes with the row objective (TLS-LZ, …)
# rows: objective => (IRLS, HQ lift, GNC, other); "--" = no such arm
rows = [
    ("Welsch",                     [num("IG  +WIrls"), num(PAPER_WELSCH_HQ), num("IG  +GNC-W"), "--"]),
    ("Geman--McClure",             [num("IG  +GM-Irls"), num("IG  +GM-HQ"), num("IG  +GNC-GM"), "--"]),
    # TLS-LZ (Le–Zach relaxation) sits under "other": its μ schedule is not the
    # GNC continuation of the GNC column (maintainer decision 2026-09-07).
    ("Trunc.\\ least sq.\\ (TLS)", [num("IG  +PoseLib"), num("IG  +TLS-HQ"), num("IG  +GNC-TLS"),
                                    tagged("LZ", "IG  +LZ") * ", " * tagged("LO\$^+\$", "IG  +TLS-LO+")]),
    ("profile marginal (\\stuU{})", ["--", "--", "--", tagged("BCD\$^{\\dagger}\$", "IG  +BCD")]),
]
io = IOBuffer()
println(io, "% Auto-generated by scripts/emit_design_table.jl from ", basename(TIMING), " (timing_table.jl stage design_table); do not hand-edit.")
println(io, "\\begin{tabular}{lcccc}")
println(io, "\t\\toprule")
println(io, "\tobjective/strategy [ms] & IRLS & HQ lift & GNC & other \\\\")   # row/column corner carries the unit
println(io, "\t\\midrule")
for (obj, cells) in rows
    println(io, "\t", obj, " & ", join(cells, " & "), " \\\\")
end
println(io, "\t\\bottomrule")
println(io, "\\end{tabular}")
mkpath(dirname(OUT)); write(OUT, String(take!(io)))
println("wrote ", OUT)
